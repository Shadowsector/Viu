_SHANYA_HEADER_RE = re.compile(r"^###\s+Шан[ьяе]к?а\s*$", re.MULTILINE | re.IGNORECASE)


def shanya_section_needs_seed(text: str) -> bool:
    """True, если блок Шани в CHARACTERS_VISION ещё пустой шаблон."""
    if not text or "CHARACTERS_VISION" not in text:
        return True
    m = _SHANYA_HEADER_RE.search(text)
    if not m:
        return True
    start = m.end()
    nxt = re.search(r"^###\s+", text[start:], re.MULTILINE)
    section = text[start : start + nxt.start()] if nxt else text[start:]
    # Пустые поля шаблона: «**Типаж:**» и сразу перевод строки
    if re.search(r"\*\*Типаж:\*\*\s*$", section, re.MULTILINE):
        return True
    if section.count("**") >= 2:
        filled = sum(
            1
            for ln in section.splitlines()
            if "**" in ln and ":" in ln and len(ln.split(":", 1)[-1].strip()) > 3
        )
        return filled < 2
    return True


def replace_shanya_section(text: str, block: str) -> str:
    """Подменить секцию ### Шаня/Шанька на block."""
    m = _SHANYA_HEADER_RE.search(text)
    if not m:
        return text.rstrip() + "\n\n" + block.strip() + "\n"
    start = m.start()
    nxt = re.search(r"^###\s+", text[m.end() :], re.MULTILINE)
    end = m.end() + nxt.start() if nxt else len(text)
    return text[:start].rstrip() + "\n\n" + block.strip() + "\n\n" + text[end:].lstrip()
