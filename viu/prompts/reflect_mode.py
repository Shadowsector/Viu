def reflect_reply_issues(text: str) -> list[str]:
    """Проблемы финального ответа reflect — для retry."""
    low = text.lower()
    issues: list[str] = []
    for phrase in BANNED_PHRASES:
        if phrase in low:
            issues.append(f"шаблон «{phrase}»")
    if _MASCULINE_RE.search(text):
        issues.append("мужской род (рад/готов/сказал)")
    return issues

